#!/usr/bin/env python3
"""Build draw/<scene>.js = src/lib.js + src/<scene>.js (the engine only prepends engine/draw/flatlib.js)."""
import glob, os
here = os.path.dirname(os.path.abspath(__file__)); ep = os.path.dirname(here)
lib = open(os.path.join(here, "lib.js")).read()
os.makedirs(os.path.join(ep, "draw"), exist_ok=True)
for f in sorted(glob.glob(os.path.join(here, "*.js"))):
    n = os.path.basename(f)
    if n == "lib.js": continue
    open(os.path.join(ep, "draw", n), "w").write(f"// GENERATED by src/build.py from src/lib.js + src/{n} — edit those, not this file.\n" + lib + "\n// ---- scene ----\n" + open(f).read())
    print("built draw/" + n)
